create extension if not exists pgcrypto;
create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 display_name text,
 role text not null default 'user' check(role in ('user','moderator','admin')),
 created_at timestamptz not null default now()
);
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
 insert into public.profiles (id, display_name)
 values (new.id, new.raw_user_meta_data ->> 'display_name');
 return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

create table if not exists public.categories (
 id bigint generated by default as identity primary key, name text not null unique
);
insert into public.categories(name) values ('Prayer'),('Quran'),('Duas'),('Daily life'),('Faith') on conflict do nothing;
create table if not exists public.questions (
 id uuid primary key default gen_random_uuid(),
 user_id uuid references auth.users(id) on delete set null,
 category_id bigint references public.categories(id),
 title varchar(180) not null check(char_length(trim(title)) >= 8),
 details varchar(700),
 is_anonymous boolean not null default true,
 status text not null default 'published' check(status in ('published','hidden','under_review')),
 created_at timestamptz not null default now()
);
create table if not exists public.answers (
 id uuid primary key default gen_random_uuid(),
 question_id uuid not null references public.questions(id) on delete cascade,
 user_id uuid references auth.users(id) on delete set null,
 body varchar(1000) not null check(char_length(trim(body)) > 0),
 source_reference text,
 status text not null default 'published' check(status in ('published','hidden','under_review')),
 created_at timestamptz not null default now()
);
create table if not exists public.votes (
 id uuid primary key default gen_random_uuid(),
 question_id uuid not null references public.questions(id) on delete cascade,
 user_id uuid not null references auth.users(id) on delete cascade,
 vote_type text not null default 'helpful' check(vote_type='helpful'),
 created_at timestamptz not null default now(), unique(question_id,user_id)
);
create table if not exists public.reports (
 id uuid primary key default gen_random_uuid(),
 question_id uuid references public.questions(id) on delete cascade,
 answer_id uuid references public.answers(id) on delete cascade,
 reporter_id uuid references auth.users(id) on delete set null,
 reason varchar(240) not null,
 status text not null default 'open' check(status in ('open','reviewed','dismissed')),
 moderator_id uuid references auth.users(id) on delete set null,
 created_at timestamptz not null default now(), reviewed_at timestamptz,
 check(question_id is not null or answer_id is not null)
);
create table if not exists public.resources (
 id uuid primary key default gen_random_uuid(), title text not null,
 resource_type text not null check(resource_type in ('quran','dua','article','external_link')),
 url text not null, source_name text, description text,
 is_verified boolean not null default false, created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.questions enable row level security;
alter table public.answers enable row level security;
alter table public.votes enable row level security;
alter table public.reports enable row level security;
alter table public.resources enable row level security;
create policy "Anyone can read categories" on public.categories for select using(true);
create policy "Read verified resources" on public.resources for select using(is_verified=true);
create policy "Read own profile" on public.profiles for select to authenticated using(auth.uid()=id);
create policy "Update own profile" on public.profiles for update to authenticated using(auth.uid()=id) with check(auth.uid()=id);
create policy "Read published questions" on public.questions for select using(status='published' or auth.uid()=user_id);
create policy "Users create own questions" on public.questions for insert to authenticated with check(auth.uid()=user_id);
create policy "Users update own questions" on public.questions for update to authenticated using(auth.uid()=user_id) with check(auth.uid()=user_id);
create policy "Read published answers" on public.answers for select using(status='published' or auth.uid()=user_id);
create policy "Users create own answers" on public.answers for insert to authenticated with check(auth.uid()=user_id);
create policy "Users update own answers" on public.answers for update to authenticated using(auth.uid()=user_id) with check(auth.uid()=user_id);
create policy "Users read own votes" on public.votes for select to authenticated using(auth.uid()=user_id);
create policy "Users create own votes" on public.votes for insert to authenticated with check(auth.uid()=user_id);
create policy "Users create reports" on public.reports for insert to authenticated with check(reporter_id is null or auth.uid()=reporter_id);
create policy "Users read own reports" on public.reports for select to authenticated using(auth.uid()=reporter_id);
